interface I18nContextType {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  locale: "en",
  setLocale: () => {},
  t: (key) => key,
});

export const useI18n = () => useContext(I18nContext);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocale] = useState<Locale>("en");

  useEffect(() => {
    // Inglês é o idioma padrão do produto. Só uma escolha EXPLÍCITA do
    // usuário no seletor de idioma altera isso.
    //
    // A detecção automática pelo idioma do navegador foi removida: ela fazia
    // todo visitante com navegador em pt-BR cair em português sem ter pedido,
    // o que dava a impressão de que o site era em português — inclusive para
    // o próprio time. O seletor continua disponível para quem quiser trocar.
    const saved = localStorage.getItem("locale") as Locale | null;
    if (saved && translations[saved]) {
      setLocale(saved);
    }
  }, []);

  const handleSetLocale = (l: Locale) => {
    setLocale(l);
    localStorage.setItem("locale", l);
  };

  const t = (key: string): string => {
    return translations[locale]?.[key] || translations["en"]?.[key] || key;
  };

  return <I18nContext.Provider value={{ locale, setLocale: handleSetLocale, t }}>{children}</I18nContext.Provider>;
};

